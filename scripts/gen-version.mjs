const { version } = JSON.parse(
  readFileSync(new URL("../package.json", import.meta.url), "utf-8")
);
const out = `// Generated by scripts/gen-version.mjs; do not edit.\nexport const VERSION = '${version}';\n`;
const path = new URL("../src/version.ts", import.meta.url);
let current = "";
try {
  current = readFileSync(path, "utf-8");
} catch {}
if (current !== out) {
  writeFileSync(path, out);
}

for (const file of [
  "../.claude-plugin/plugin.json",
  "../server.json",
  "../gemini-extension.json",
]) {
  const url = new URL(file, import.meta.url);
  const text = readFileSync(url, "utf-8");
  const json = JSON.parse(text);
  json.version = version;
  for (const pkg of json.packages ?? []) {
    pkg.version = version;
  }
  const next = `${JSON.stringify(json, null, 2)}\n`;
  if (next !== text) {
    writeFileSync(url, next);
  }
}

{
  const url = new URL("../install.sh", import.meta.url);
  const text = readFileSync(url, "utf-8");
  const next = text.replace(/^VERSION='[^']*'$/m, `VERSION='${version}'`);
  if (!/^VERSION='/m.test(text)) {
    throw new Error("install.sh has no VERSION='...' line");
  }
  if (next !== text) {
    writeFileSync(url, next);
  }
}

const skillDir = new URL("../skills/better-tg-cli/", import.meta.url);
const { readdirSync, rmSync } = await import("node:fs");
const skillNames = readdirSync(skillDir)
  .filter((f) => f.endsWith(".md"))
  .sort();
if (!skillNames.includes("SKILL.md")) {
  throw new Error("skills/better-tg-cli has no SKILL.md");
}
const skillFiles = Object.fromEntries(
  skillNames.map((f) => [f, readFileSync(new URL(f, skillDir), "utf-8")])
);
function pruneSkillCopy(root) {
  const dir = new URL(`../${root}/skills/better-tg-cli/`, import.meta.url);
  let present = [];
  try {
    present = readdirSync(dir);
  } catch {}
  for (const f of present) {
    if (!(f in skillFiles)) {
      rmSync(new URL(f, dir), { force: true });
    }
  }
}
