const NAMES = {
  "": "Manifest",
  "/properties/author": "ManifestAuthor",
  "/properties/engines": "ManifestEngines",
  "/properties/permissions/items": "Permission",
  "/properties/secrets/items": "ManifestSecret",
  "/properties/secrets/items/properties/inject": "SecretInject",
  "/properties/settings/additionalProperties": "SettingSchema",
  "/properties/storage": "ManifestStorage",
  "/properties/commands/items": "ManifestCommand",
  "/properties/commands/items/properties/effects/items": "Effect",
  "/properties/commands/items/properties/input": "CommandSchema",
  "/properties/commands/items/properties/output": "CommandSchema",
  "/properties/triggers/items": "ManifestTrigger",
  "/properties/onboarding": "ManifestOnboarding",
};

const pascal = (s) =>
  s.replaceAll(/(^|[^A-Za-z0-9])([a-z])/g, (_, __, c) => c.toUpperCase());

const doc = (text, indent) => {
  if (!text) {
    return "";
  }
  const safe = text.replaceAll("*/", "*\\/");
  return `${indent}/** ${safe} */\n`;
};

const key = (k) =>
  /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k);

const PRIMITIVE = {
  string: "string",
  integer: "number",
  number: "number",
  boolean: "boolean",
  null: "null",
};

/**
 * TypeScript declarations of the plugin manifest, generated from its JSON Schema: one interface or
 * alias per named position (NAMES), the `$defs` as string aliases, descriptions as JSDoc.
 */
export function manifestTypesSource(schema, specVersion) {
  const decls = [];
  const named = new Set();

  const typeOf = (s, ptr, indent) => {
    if (ptr in NAMES && ptr !== "") {
      emit(s, ptr);
      return NAMES[ptr];
    }
    return inline(s, ptr, indent);
  };

  const inline = (s, ptr, indent) => {
    if (s.$ref) {
      return pascal(s.$ref.replace("#/$defs/", ""));
    }
    if (s.enum) {
      return s.enum.map((v) => JSON.stringify(v)).join(" | ");
    }
    const types = Array.isArray(s.type) ? s.type : [s.type];
    if (types.length > 1) {
      return [...new Set(types.map((t) => PRIMITIVE[t]))].join(" | ");
    }
    if (s.type === "array") {
      const item = typeOf(s.items, `${ptr}/items`, indent);
      return /[ |]/.test(item) ? `(${item})[]` : `${item}[]`;
    }
    if (s.type === "object") {
      if (s.properties) {
        return objectBody(s, ptr, indent);
      }
      if (
        s.additionalProperties &&
        typeof s.additionalProperties === "object"
      ) {
        return `Record<string, ${typeOf(s.additionalProperties, `${ptr}/additionalProperties`, indent)}>`;
      }
      return "Record<string, unknown>";
    }
    return PRIMITIVE[s.type] ?? "unknown";
  };

  const objectBody = (s, ptr, indent) => {
    const inner = `${indent}  `;
    const required = new Set(s.required);
    const lines = Object.entries(s.properties).map(
      ([k, p]) =>
        `${doc(p.description, inner)}${inner}${key(k)}${required.has(k) ? "" : "?"}: ${typeOf(p, `${ptr}/properties/${k}`, inner)};\n`
    );
    return `{\n${lines.join("")}${indent}}`;
  };

  const emit = (s, ptr) => {
    const name = NAMES[ptr];
    if (named.has(name)) {
      return;
    }
    named.add(name);
    const body =
      s.type === "object" && s.properties
        ? objectBody(s, ptr, "")
        : inline(s, ptr, "");
    const head = doc(s.description, "");
    decls.push(
      s.type === "object" && s.properties
        ? `${head}export interface ${name} ${body}\n`
        : `${head}export type ${name} = ${body};\n`
    );
  };

  for (const [name, def] of Object.entries(schema.$defs ?? {})) {
    decls.push(
      `${doc(def.description, "")}export type ${pascal(name)} = string;\n`
    );
  }
  named.add("Manifest");
  const root = `${doc(schema.title, "")}export interface Manifest ${objectBody(schema, "", "")}\n`;
  return `// Generated by scripts/gen-version.mjs from schemas/tg-plugin; do not edit.\n/** The spec version these types describe. */\nexport const SPEC_VERSION = ${JSON.stringify(specVersion)};\n\n${decls.join("\n")}\n${root}`;
}
